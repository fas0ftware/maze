"""Make the hashes Maze runs on. Nothing it writes contains a plain-text password.

  python -m app.hashtool decoys SOURCE.json [-o config/layers.json]
      SOURCE is a layer config whose decoys are still plain text, for example
      {"layer_count": 3, "layers": {"1": {"decoys": ["admin123", ...]},
                                    "2": {"decoys": ["root!2024", ...]}}}
      (a bare list is accepted for a layer). The output is the same config with
      every decoy replaced by its Argon2id hash and a fresh decoy_kdf salt.
      Keep SOURCE out of the repository (config/*.plain.json is git-ignored).

  python -m app.hashtool real [--config config/layers.json] [--stdin]
      Reads the real password (prompted twice, or one line from stdin) and
      prints a MAZE_REAL_PASSWORD_HASH=... line. Refuses a password that is one
      of the decoys in --config.

Both commands take --opslimit / --memlimit-kib to set the Argon2id cost.
"""

import argparse
import copy
import getpass
import json
import sys
from pathlib import Path

from . import core
from .config import (
    REAL_PASSWORD_HASH_ENV,
    ConfigError,
    load_layer_config,
    read_json_config,
    real_password_warnings,
)

DEFAULT_OPSLIMIT = 2
DEFAULT_MEMLIMIT_KIB = 19 * 1024  # 19 MiB, t=2: the OWASP minimum for Argon2id


def hash_layer_config(source: dict, opslimit=DEFAULT_OPSLIMIT,
                      memlimit_kib=DEFAULT_MEMLIMIT_KIB, salt=None) -> dict:
    """Return a copy of source with every plain-text decoy replaced by its hash."""
    if not isinstance(source, dict) or not isinstance(source.get("layers"), dict):
        raise ConfigError("source must be a JSON object with a 'layers' object")
    kdf = core.make_kdf(salt or core.random_salt(), opslimit, memlimit_kib)
    out = copy.deepcopy(source)
    out["decoy_kdf"] = {"salt": core.b64encode(bytes(kdf.salt)), "opslimit": opslimit,
                        "memlimit_kib": memlimit_kib}
    for name, entry in source["layers"].items():
        if isinstance(entry, list):
            entry = {"decoys": entry}
        if not isinstance(entry, dict):
            raise ConfigError(f"layers.{name} must be a list or an object")
        entry = dict(entry)
        if "decoys" in entry:
            words = entry["decoys"]
            if not isinstance(words, list) or not all(isinstance(w, str) and w for w in words):
                raise ConfigError(f"layers.{name}.decoys must be a list of non-empty strings")
            entry["decoys"] = [core.b64encode(core.hash_password(kdf, w)) for w in words]
        out["layers"][name] = entry
    out["_comment"] = ("Generated by python -m app.hashtool decoys. Decoys are Argon2id "
                       "hashes; the real password is not in this file.")
    return out


def real_password_hash(password: str, cfg: dict, opslimit=DEFAULT_OPSLIMIT,
                       memlimit_kib=DEFAULT_MEMLIMIT_KIB, salt=None) -> str:
    """PHC string for MAZE_REAL_PASSWORD_HASH. Refuses a password that is a decoy."""
    if not password:
        raise ConfigError("the real password must not be empty")
    guess = core.hash_password(cfg["decoy_kdf"], password)
    for layer, hashes in cfg["decoys"].items():
        if guess in hashes:
            raise ConfigError(f"this password is a layer {layer} decoy. Choose another one.")
    kdf = core.make_kdf(salt or core.random_salt(), opslimit, memlimit_kib)
    return core.encode_phc(kdf, core.hash_password(kdf, password))


def _read_password(from_stdin: bool) -> str:
    if from_stdin:
        return sys.stdin.readline().rstrip("\r\n")
    first = getpass.getpass("Real password: ")
    if getpass.getpass("Repeat: ") != first:
        raise ConfigError("the two passwords differ")
    return first


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.hashtool",
                                     description=__doc__.splitlines()[0])
    parser.add_argument("--opslimit", type=int, default=DEFAULT_OPSLIMIT)
    parser.add_argument("--memlimit-kib", type=int, default=DEFAULT_MEMLIMIT_KIB)
    sub = parser.add_subparsers(dest="command", required=True)
    decoys = sub.add_parser("decoys", help="hash the decoys of a plain-text layer config")
    decoys.add_argument("source", type=Path)
    decoys.add_argument("-o", "--out", type=Path)
    real = sub.add_parser("real", help="hash the real password")
    real.add_argument("--config", type=Path)
    real.add_argument("--stdin", action="store_true", help="read one line from stdin")
    args = parser.parse_args(argv)

    try:
        if args.command == "decoys":
            result = hash_layer_config(read_json_config(args.source), args.opslimit,
                                       args.memlimit_kib)
            text = json.dumps(result, indent=2) + "\n"
            if args.out:
                args.out.write_text(text, encoding="utf-8")
                load_layer_config(args.out)  # validate what was written
                print(f"Wrote {args.out}", file=sys.stderr)
            else:
                sys.stdout.write(text)
        else:
            cfg = load_layer_config(args.config)
            password = _read_password(args.stdin)
            for warning in real_password_warnings(password):
                print(f"[hashtool] WARNING: {warning}", file=sys.stderr)
            phc = real_password_hash(password, cfg, args.opslimit, args.memlimit_kib)
            print(f"{REAL_PASSWORD_HASH_ENV}='{phc}'")
    except ConfigError as exc:
        print(f"[hashtool] {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
